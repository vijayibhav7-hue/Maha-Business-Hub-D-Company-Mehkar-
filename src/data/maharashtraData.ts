export const getTalukasByDistrict = (districtName: string): { name: string; nameMr: string }[] => {
  if (!districtName || districtName === 'All') return [];
  const matched = MAHARASHTRA_DISTRICTS_DATA.find(
    (d) => d.name.toLowerCase() === districtName.toLowerCase() || d.nameMr.includes(districtName)
  );
  return matched ? matched.talukas : [];
};

export const autoDetectLocation = (text: string): { district: string; taluka: string; village: string } => {
  const clean = text.toLowerCase();
  let detectedDistrict = 'Buldhana';
  let detectedTaluka = 'Mehkar';
  let detectedVillage = 'Mehkar';

  for (const dist of MAHARASHTRA_DISTRICTS_DATA) {
    if (clean.includes(dist.name.toLowerCase()) || clean.includes(dist.nameMr.toLowerCase())) {
      detectedDistrict = dist.name;
      break;
    }
  }

  const talukaList = getTalukasByDistrict(detectedDistrict);
  for (const tal of talukaList) {
    if (clean.includes(tal.name.toLowerCase()) || clean.includes(tal.nameMr.toLowerCase())) {
      detectedTaluka = tal.name;
      detectedVillage = tal.name;
      break;
    }
  }

  // Fallback scan across all talukas if district was default
  if (detectedDistrict === 'Buldhana' && detectedTaluka === 'Mehkar') {
    for (const dist of MAHARASHTRA_DISTRICTS_DATA) {
      for (const tal of dist.talukas) {
        if (clean.includes(tal.name.toLowerCase()) || clean.includes(tal.nameMr.toLowerCase())) {
          detectedDistrict = dist.name;
          detectedTaluka = tal.name;
          detectedVillage = tal.name;
          break;
        }
      }
    }
  }

  return { district: detectedDistrict, taluka: detectedTaluka, village: detectedVillage };
};
